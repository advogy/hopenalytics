<?php

namespace App\Console\Commands;

use App\Support\IndonesiaIp;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Http;

/**
 * Rebuilds resources/geo/indonesia-ip-ranges.php (what SetLocale uses to pick Indonesian
 * for visitors in Indonesia) from APNIC's public delegation list. Run it locally every few
 * months and commit the result: the shared host has no reason to download it itself.
 */
class UpdateIndonesiaIpRanges extends Command
{
    protected $signature = 'geo:update-indonesia-ip
        {--source=https://ftp.apnic.net/stats/apnic/delegated-apnic-latest : APNIC delegation file, as a URL or a local path}';

    protected $description = 'Refresh the list of Indonesian IP ranges used to choose the display language';

    public function handle(): int
    {
        $source = (string) $this->option('source');
        $body = str_starts_with($source, 'http')
            ? Http::timeout(60)->get($source)->throw()->body()
            : @file_get_contents($source);

        if (! is_string($body) || $body === '') {
            $this->error("Could not read {$source}.");

            return self::FAILURE;
        }

        $ipv4 = [];
        $ipv6 = [];

        // Format: registry|cc|type|start|value|date|status — for ipv4 "value" is the number
        // of addresses, for ipv6 it is the prefix length.
        foreach (preg_split('/\R/', $body) as $line) {
            $fields = explode('|', $line);

            if (count($fields) < 7 || $fields[1] !== 'ID' || ! in_array($fields[6], ['allocated', 'assigned'], true)) {
                continue;
            }

            if ($fields[2] === 'ipv4' && ($start = ip2long($fields[3])) !== false) {
                $ipv4[] = [$start, $start + (int) $fields[4] - 1];
            } elseif ($fields[2] === 'ipv6' && ($binary = @inet_pton($fields[3])) !== false && strlen($binary) === 16) {
                $ipv6[] = [bin2hex($binary), bin2hex(self::lastAddress($binary, (int) $fields[4]))];
            }
        }

        // A suspiciously short list means a truncated or changed download; keep the old file.
        if (count($ipv4) < 1000) {
            $this->error('Found only '.count($ipv4).' Indonesian IPv4 blocks — not overwriting the existing list.');

            return self::FAILURE;
        }

        $ipv4 = self::merge($ipv4, fn (int $end) => $end + 1);
        $ipv6 = self::merge($ipv6, fn (string $end) => $end);

        $path = resource_path(IndonesiaIp::DATA_PATH);
        @mkdir(dirname($path), 0755, true);
        file_put_contents($path, self::render($ipv4, $ipv6));

        $this->info(sprintf('Wrote %d IPv4 and %d IPv6 ranges to %s.', count($ipv4), count($ipv6), $path));

        return self::SUCCESS;
    }

    /** The last address of the block that starts at $start with the given prefix length. */
    private static function lastAddress(string $start, int $prefix): string
    {
        $bytes = array_values(unpack('C*', $start));

        for ($bit = max(0, $prefix); $bit < 128; $bit++) {
            $bytes[intdiv($bit, 8)] |= 0x80 >> ($bit % 8);
        }

        return pack('C*', ...$bytes);
    }

    /**
     * Sorts by start and joins ranges that overlap or (when $next can tell) touch, so the
     * binary search in IndonesiaIp sees non-overlapping ranges.
     */
    private static function merge(array $ranges, callable $next): array
    {
        usort($ranges, fn ($a, $b) => IndonesiaIp::compare($a[0], $b[0]));
        $merged = [];

        foreach ($ranges as [$start, $end]) {
            $last = count($merged) - 1;

            if ($last >= 0 && IndonesiaIp::compare($start, $next($merged[$last][1])) <= 0) {
                if (IndonesiaIp::compare($end, $merged[$last][1]) > 0) {
                    $merged[$last][1] = $end;
                }
            } else {
                $merged[] = [$start, $end];
            }
        }

        return $merged;
    }

    private static function render(array $ipv4, array $ipv6): string
    {
        $lines = [
            '<?php',
            '',
            '// Generated by `php artisan geo:update-indonesia-ip` from APNIC\'s delegation list on '.now()->toDateString().'.',
            '// Do not edit by hand. IPv4 as integers, IPv6 as 32-character hex, each [first, last].',
            '',
            'return [',
            "    'ipv4' => [",
        ];

        foreach ($ipv4 as [$start, $end]) {
            $lines[] = "        [{$start}, {$end}],";
        }

        $lines[] = '    ],';
        $lines[] = "    'ipv6' => [";

        foreach ($ipv6 as [$start, $end]) {
            $lines[] = "        ['{$start}', '{$end}'],";
        }

        $lines[] = '    ],';
        $lines[] = '];';

        return implode("\n", $lines)."\n";
    }
}
